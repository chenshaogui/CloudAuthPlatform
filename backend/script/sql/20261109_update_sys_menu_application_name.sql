-- 菜单显示名调整：应用管理 -> 应用菜单管理
-- 创建时间：2026-11-09
-- 用途：sys_menu 中 menu_id=134 的菜单实际维护「应用级菜单(menuType='A')及其应用下菜单树」，
--       与「客户端管理」「菜单管理」语义易混淆，显示名统一为「应用菜单管理」。
-- 兼容性：仅修改显示名，不改动 path / component / perms，不影响已有角色授权；可重复执行。
-- =============================================================

UPDATE `sys_menu`
SET `menu_name` = '应用菜单管理'
WHERE `menu_id` = 134
  AND `menu_name` = '应用管理';

